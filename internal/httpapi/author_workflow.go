package httpapi

import (
	"encoding/json"
	"fmt"
	"net/http"
	"os"
	"strings"
)

// AuthorWorkflowPath is where the generated workflow must live in a repository.
// GitHub only runs workflows from this exact directory.
const AuthorWorkflowPath = ".github/workflows/rezehub-notify.yml"

// workflowNotifyPath is the hub endpoint the generated workflow calls. It is a
// constant so the generator and the route registration cannot drift apart.
const workflowNotifyPath = "/api/v1/github-release-notify"

// workflowPlatformRules is the per-platform matcher set a repository's release
// must satisfy, embedded into the generated workflow as a JSON object.
//
// The rules travel with the notification instead of living only in the hub for
// one reason: the author is editing them on the same screen that generates this
// file. Sending them makes the file the single record of "what this repository
// considers a release", so changing an asset name means editing the file the
// author already owns rather than a second, invisible copy inside the hub.
type workflowPlatformRules struct {
	// Shared matches one archive that serves every platform.
	Shared string `json:"shared,omitempty"`
	// Windows and Android match per-platform archives when split delivery is on.
	Windows string `json:"windows,omitempty"`
	Android string `json:"android,omitempty"`
}

// workflowRuleSet builds the matcher set a mod's current configuration implies.
func workflowRuleSet(mod Mod) workflowPlatformRules {
	if len(mod.GitHubPlatformAssets) == 0 {
		return workflowPlatformRules{Shared: mod.GitHubAssetRegex}
	}
	rules := workflowPlatformRules{}
	for _, rule := range mod.GitHubPlatformAssets {
		switch rule.Platform {
		case "windows":
			rules.Windows = rule.Regex
		case "android":
			rules.Android = rule.Regex
		}
	}
	return rules
}

// renderAuthorWorkflow returns the workflow an author copies into their
// repository unchanged. It is generated rather than hand-written in the docs so
// the hub URL, endpoint path, and matchers always match the configuration that
// produced it: a stale snippet is the one failure an author cannot diagnose from
// the outside.
//
// It embeds the platform regexes because the notification's job is to tell the
// hub "this specific release has an asset I consider publishable". Without them
// every release would look like news, including releases that only ship docs or
// notes.
func renderAuthorWorkflow(hubURL string, rules workflowPlatformRules) string {
	rulesJSON, _ := json.Marshal(rules)
	rulesLine := strings.TrimSpace(string(rulesJSON))
	if rulesLine == "" {
		rulesLine = "{}"
	}

	body := fmt.Sprintf(`# Generated by RezeHub. Copy this file to %s in your repository.
#
# It tells RezeHub that a new release exists, so the mod page updates within
# seconds instead of waiting for the periodic check.
#
# The PC/Android patterns below are the ones you configured on RezeHub. Edit them
# here if your asset names change; this file is the record of what counts as a
# publishable release for this repository. RezeHub matches the repository it is
# bound to, so the file contains no secret.
name: Notify RezeHub

on:
  release:
    # `+"`published`"+` fires only when a release actually goes out. `+"`created`"+` would
    # also fire for drafts, which have no downloadable assets yet.
    types: [published]

# Nothing is written back to this repository.
permissions: {}

jobs:
  notify:
    runs-on: ubuntu-latest
    timeout-minutes: 5
    steps:
      - name: Notify RezeHub of the release
        continue-on-error: true
        env:
          # Which file names count as this repository's build. "shared" serves
          # every platform; windows/android apply when the platforms ship apart.
          # A literal block keeps backslashes exact: inside this JSON, "\d" is
          # a regex digit class, and no YAML quoting layer may touch it.
          REZEHUB_RULES: |-
            %s
        run: |
          set -euo pipefail
          curl --fail-with-body --silent --show-error --max-time 20 \
            --retry 3 --retry-delay 5 --retry-all-errors \
            -H 'Content-Type: application/json' \
            --data "{\"owner\":\"${GITHUB_REPOSITORY%%/*}\",\"repo\":\"${GITHUB_REPOSITORY#*/}\",\"version\":\"${GITHUB_REF_NAME}\",\"rules\":${REZEHUB_RULES}}" \
            "%s%s"
`, AuthorWorkflowPath, rulesLine, strings.TrimRight(hubURL, "/"), workflowNotifyPath)
	return body
}

// authorWorkflow serves the copy-ready workflow for one mod. It is author-only
// and only meaningful for GitHub-backed mods: a local mod has nothing to be
// notified about.
func (s *Store) authorWorkflow(w http.ResponseWriter, r *http.Request, modID, userID string, isAdmin bool) {
	if r.Method != http.MethodGet {
		writeError(w, 405, "method_not_allowed", "method is not supported")
		return
	}
	s.mu.RLock()
	var mod *Mod
	for i := range s.Catalog.Mods {
		if s.Catalog.Mods[i].ID == modID {
			m := s.Catalog.Mods[i]
			mod = &m
			break
		}
	}
	s.mu.RUnlock()
	if mod == nil {
		writeError(w, 404, "not_found", "mod was not found")
		return
	}
	if mod.Author.ID != userID && !isAdmin {
		writeError(w, 403, "forbidden", "administrator or author permission required")
		return
	}
	if mod.GetSourceType() != "github_releases" {
		writeError(w, 400, "not_github_source", "mod is not configured for github_releases")
		return
	}
	hubURL := hubURLForRequest(r)
	rules := workflowRuleSet(*mod)
	writeJSON(w, http.StatusOK, map[string]any{
		"mod_id":     mod.ID,
		"path":       AuthorWorkflowPath,
		"owner":      mod.GitHubOwner,
		"repo":       mod.GitHubRepo,
		"rules":      rules,
		"content":    renderAuthorWorkflow(hubURL, rules),
		"notify_url": hubURL + workflowNotifyPath,
	})
}

// authorWorkflowTemplate serves a workflow body for the draft form, where the
// regexes are being typed but no mod exists yet. The caller supplies the rules
// it is about to save, so the preview matches what will actually be stored.
func (s *Store) authorWorkflowTemplate(w http.ResponseWriter, r *http.Request) {
	if _, ok := s.requireSession(w, r); !ok {
		return
	}
	if r.Method != http.MethodGet {
		writeError(w, 405, "method_not_allowed", "method is not supported")
		return
	}
	query := r.URL.Query()
	rules := workflowPlatformRules{
		Shared:  strings.TrimSpace(query.Get("shared")),
		Windows: strings.TrimSpace(query.Get("windows")),
		Android: strings.TrimSpace(query.Get("android")),
	}
	hubURL := hubURLForRequest(r)
	writeJSON(w, http.StatusOK, map[string]any{
		"path":       AuthorWorkflowPath,
		"rules":      rules,
		"content":    renderAuthorWorkflow(hubURL, rules),
		"notify_url": hubURL + workflowNotifyPath,
	})
}

// hubURLForRequest is the public base URL an author's workflow should call. An
// explicit SUBMODHUB_PUBLIC_URL wins because a reverse proxy that rewrites Host
// would otherwise hand the author an address that only works on the proxy's
// internal network; without it the request's own host is the best available
// answer, and it is by definition one the author can reach.
func hubURLForRequest(r *http.Request) string {
	if configured := strings.TrimRight(strings.TrimSpace(os.Getenv("SUBMODHUB_PUBLIC_URL")), "/"); configured != "" {
		return configured
	}
	scheme := "https"
	if r.TLS == nil {
		if proto := strings.TrimSpace(r.Header.Get("X-Forwarded-Proto")); proto != "" {
			scheme = strings.ToLower(proto)
		} else {
			scheme = "http"
		}
	}
	return scheme + "://" + r.Host
}
